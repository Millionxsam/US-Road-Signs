using System;
using System.Collections.Generic;

namespace USRoadSigns.Digital
{
    /// <summary>
    /// 5 x 7 dot-matrix font used by changeable message signs (NTCIP 1203 style single-stroke font).
    /// Letters and digits are a fixed 5 columns wide; punctuation is narrower, like the proportional fonts on
    /// full-matrix signs. Lower case is shown as upper case.
    /// Arrows: &lt; left, &gt; right, ^ up, ~ down.
    /// </summary>
    public static class LedFont
    {
        public const int Height = 7;
        public const int CharSpacing = 1;

        /// <summary>One glyph: <see cref="Width"/> columns, rows top to bottom.</summary>
        public sealed class Glyph
        {
            public readonly int Width;
            private readonly bool[] m_Bits;

            public Glyph(string[] rows)
            {
                Width = rows[0].Length;
                m_Bits = new bool[Width * Height];
                for (int y = 0; y < Height; y++)
                {
                    if (rows[y].Length != Width)
                        throw new ArgumentException("Glyph rows must have equal length");
                    for (int x = 0; x < Width; x++)
                        m_Bits[y * Width + x] = rows[y][x] == '#';
                }
            }

            public bool this[int x, int y] => m_Bits[y * Width + x];
        }

        private static readonly Dictionary<char, Glyph> s_Glyphs = Build();
        private static readonly Glyph s_Unknown = s_Glyphs['?'];

        public static Glyph Get(char c)
        {
            c = char.ToUpperInvariant(c);
            return s_Glyphs.TryGetValue(c, out Glyph g) ? g : s_Unknown;
        }

        public static bool IsSupported(char c) => s_Glyphs.ContainsKey(char.ToUpperInvariant(c));

        /// <summary>Width in LED columns of a line of text.</summary>
        public static int MeasureLine(string text, int spacing = CharSpacing)
        {
            if (string.IsNullOrEmpty(text))
                return 0;
            int width = 0;
            for (int i = 0; i < text.Length; i++)
                width += Get(text[i]).Width + (i > 0 ? spacing : 0);
            return width;
        }

        private static Dictionary<char, Glyph> Build()
        {
            var map = new Dictionary<char, Glyph>();
            void G(char c, string rows) => map[c] = new Glyph(rows.Split('|'));

            G('A', ".###.|#...#|#...#|#####|#...#|#...#|#...#");
            G('B', "####.|#...#|#...#|####.|#...#|#...#|####.");
            G('C', ".###.|#...#|#....|#....|#....|#...#|.###.");
            G('D', "####.|#...#|#...#|#...#|#...#|#...#|####.");
            G('E', "#####|#....|#....|####.|#....|#....|#####");
            G('F', "#####|#....|#....|####.|#....|#....|#....");
            G('G', ".###.|#...#|#....|#.###|#...#|#...#|.####");
            G('H', "#...#|#...#|#...#|#####|#...#|#...#|#...#");
            G('I', "###|.#.|.#.|.#.|.#.|.#.|###");
            G('J', "..###|...#.|...#.|...#.|...#.|#..#.|.##..");
            G('K', "#...#|#..#.|#.#..|##...|#.#..|#..#.|#...#");
            G('L', "#....|#....|#....|#....|#....|#....|#####");
            G('M', "#...#|##.##|#.#.#|#.#.#|#...#|#...#|#...#");
            G('N', "#...#|#...#|##..#|#.#.#|#..##|#...#|#...#");
            G('O', ".###.|#...#|#...#|#...#|#...#|#...#|.###.");
            G('P', "####.|#...#|#...#|####.|#....|#....|#....");
            G('Q', ".###.|#...#|#...#|#...#|#.#.#|#..#.|.##.#");
            G('R', "####.|#...#|#...#|####.|#.#..|#..#.|#...#");
            G('S', ".###.|#...#|#....|.###.|....#|#...#|.###.");
            G('T', "#####|..#..|..#..|..#..|..#..|..#..|..#..");
            G('U', "#...#|#...#|#...#|#...#|#...#|#...#|.###.");
            G('V', "#...#|#...#|#...#|#...#|#...#|.#.#.|..#..");
            G('W', "#...#|#...#|#...#|#.#.#|#.#.#|#.#.#|.#.#.");
            G('X', "#...#|#...#|.#.#.|..#..|.#.#.|#...#|#...#");
            G('Y', "#...#|#...#|.#.#.|..#..|..#..|..#..|..#..");
            G('Z', "#####|....#|...#.|..#..|.#...|#....|#####");

            G('0', ".###.|#...#|#..##|#.#.#|##..#|#...#|.###.");
            G('1', "..#..|.##..|..#..|..#..|..#..|..#..|.###.");
            G('2', ".###.|#...#|....#|...#.|..#..|.#...|#####");
            G('3', "#####|...#.|..#..|...#.|....#|#...#|.###.");
            G('4', "...#.|..##.|.#.#.|#..#.|#####|...#.|...#.");
            G('5', "#####|#....|####.|....#|....#|#...#|.###.");
            G('6', "..##.|.#...|#....|####.|#...#|#...#|.###.");
            G('7', "#####|....#|...#.|..#..|.#...|.#...|.#...");
            G('8', ".###.|#...#|#...#|.###.|#...#|#...#|.###.");
            G('9', ".###.|#...#|#...#|.####|....#|...#.|.##..");

            G(' ', "...|...|...|...|...|...|...");
            G('.', "..|..|..|..|..|##|##");
            G(',', "..|..|..|..|##|##|#.");
            G(':', "..|##|##|..|##|##|..");
            G(';', "..|##|##|..|##|##|#.");
            G('!', "#|#|#|#|#|.|#");
            G('?', ".###.|#...#|....#|...#.|..#..|.....|..#..");
            G('\'', "#|#|.|.|.|.|.");
            G('"', "#.#|#.#|...|...|...|...|...");
            G('-', "....|....|....|####|....|....|....");
            G('+', ".....|..#..|..#..|#####|..#..|..#..|.....");
            G('=', ".....|.....|#####|.....|#####|.....|.....");
            G('*', ".....|#.#.#|.###.|#####|.###.|#.#.#|.....");
            G('/', ".....|....#|...#.|..#..|.#...|#....|.....");
            G('_', ".....|.....|.....|.....|.....|.....|#####");
            G('(', "..#|.#.|#..|#..|#..|.#.|..#");
            G(')', "#..|.#.|..#|..#|..#|.#.|#..");
            G('&', ".##..|#..#.|#.#..|.#...|#.#.#|#..#.|.##.#");
            G('%', "##...|##..#|...#.|..#..|.#...|#..##|...##");
            G('$', "..#..|.####|#.#..|.###.|..#.#|####.|..#..");
            G('#', ".#.#.|.#.#.|#####|.#.#.|#####|.#.#.|.#.#.");
            G('@', ".###.|#...#|#.###|#.#.#|#.###|#....|.###.");

            // Arrows
            G('<', ".......|..#....|.##....|#######|.##....|..#....|.......");
            G('>', ".......|....#..|....##.|#######|....##.|....#..|.......");
            G('^', "..#..|.###.|#.#.#|..#..|..#..|..#..|..#..");
            G('~', "..#..|..#..|..#..|..#..|#.#.#|.###.|..#..");
            return map;
        }
    }
}
